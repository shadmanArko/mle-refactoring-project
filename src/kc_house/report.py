"""Render the model card from a training report, so docs never drift from numbers."""


def _table(headers: list[str], rows: list[list[str]]) -> str:
    lines = [
        "| " + " | ".join(headers) + " |",
        "|" + "|".join("---" for _ in headers) + "|",
    ]
    lines += ["| " + " | ".join(row) + " |" for row in rows]
    return "\n".join(lines)


def _usd(value: float) -> str:
    sign = "-" if round(value) < 0 else ""
    return f"{sign}${abs(value):,.0f}"


def _r2(value: float) -> str:
    return f"{value + 0.0:.3f}" if abs(value) >= 0.0005 else "0.000"


def _metrics_table(metrics: dict) -> str:
    return _table(
        ["Metric", "Value"],
        [
            ["R²", _r2(metrics["r2"])],
            [
                "Typical error (median)",
                f"{metrics['median_abs_pct_error']:.1f}% of the price",
            ],
            ["Mean absolute error", _usd(metrics["mae"])],
            ["RMSE", _usd(metrics["rmse"])],
            ["Average bias", _usd(metrics["mean_error"])],
        ],
    )


def _band_table(bands: list[dict]) -> str:
    return _table(
        ["Quartile", "Price range", "Houses", "Typical error", "Average bias"],
        [
            [
                str(band["band"]),
                f"{_usd(band['price_min'])} to {_usd(band['price_max'])}",
                str(band["houses"]),
                f"{band['median_abs_pct_error']:.1f}%",
                _usd(band["mean_error"]),
            ]
            for band in bands
        ],
    )


def _bias_note(bands: list[dict]) -> str:
    cheapest, priciest = bands[0]["mean_error"], bands[-1]["mean_error"]
    if cheapest > 0 > priciest:
        return (
            "The model pulls estimates toward the middle: cheap houses tend to be "
            "overestimated and the most expensive underestimated."
        )
    return "Errors are not evenly spread across prices; see average bias by quartile."


def _gate(report: dict) -> str:
    models = [row for row in report["comparison"] if row["role"] != "baseline"]
    best = max(models, key=lambda row: row["cv_r2_mean"])
    worst = min(models, key=lambda row: row["cv_r2_mean"])
    spread = best["cv_r2_mean"] - worst["cv_r2_mean"]
    floor = report["min_acceptable_r2"]
    verdict = "not_warranted" if best["cv_r2_mean"] >= floor else "conditional"
    return (
        f"**Verdict: `{verdict}`.** The data is 19 tabular columns with no text or "
        f"images. The best classical model ({best['name']}) reaches a cross-validated "
        f"R² of {best['cv_r2_mean']:.3f} against a floor of {floor:.2f}; the spread "
        f"across classical families is {spread:.3f}.\n\n"
        "Revisit if: the dataset grows past roughly 1 million sales, listing text or "
        "photos are added as inputs, or classical models stop clearing the floor "
        "after retraining."
    )


def _header(report: dict) -> str:
    meta = report["metadata"]
    return f"""# Model card: King County house price estimator

Generated by `kc_house.train` on {meta["trained_at"]} (git `{meta["git_sha"][:7]}`).
Every number below comes from `metrics.json`; do not edit by hand.

## Intended use

Give a rough sale-price estimate for a house in King County, Washington, to help a
buyer or seller judge a fair price. **Not** for appraisal, lending, insurance or any
decision with legal or financial consequences."""


def _data(report: dict) -> str:
    meta = report["metadata"]
    start, end = meta["sale_dates"]
    return f"""## Data

{meta["data_rows"]:,} house sales from {start} to {end} (one year); one implausible
record is removed. Split {meta["train_rows"]:,} train / {meta["test_rows"]:,} test,
seed {meta["random_state"]}. Dataset hash `{meta["data_sha256"][:12]}`."""


def _model(report: dict) -> str:
    settings = "\n".join(
        f"- `{name.removeprefix('model__')}`: {value}"
        for name, value in sorted(report["best_params"].items())
    )
    return f"""## Model

```mermaid
flowchart LR
    A[Raw house columns] --> B[Clean and engineer 19 features]
    B --> C[Gradient-boosted trees]
    C --> D[Price]
```

Gradient-boosted trees, tuned by {report["metadata"]["search_iterations"]} random
settings with {report["metadata"]["cv_folds"]}-fold cross-validation on training data
only. Chosen settings:

{settings}

The notebook's polynomial ElasticNet stays in the comparison as the documented
reference."""


def _performance(report: dict) -> str:
    return f"""## Performance (held-out test set, used once to judge the champion)

{_metrics_table(report["test_metrics"])}

Stopping floor: held-out R² of at least {report["min_acceptable_r2"]:.2f}. Met."""


def _comparison(report: dict) -> str:
    rows = [
        [
            f"`{row['name']}`",
            row["role"],
            f"{_r2(row['cv_r2_mean'])} ± {row['cv_r2_std']:.3f}",
            _r2(row["test_r2"]) if "test_r2" in row else "not used",
        ]
        for row in report["comparison"]
    ]
    return f"""## What it beat

{_table(["Model", "Role", "Cross-validated R²", "Test R²"], rows)}

Baselines are scored before any tuning. Candidates are judged on cross-validation
only. The reference's test score is reported for information, not used to choose."""


def _robustness(report: dict) -> str:
    rows = [
        [name, _r2(m["r2"]), _usd(m["mae"]), f"{m['median_abs_pct_error']:.1f}%"]
        for name, m in report["split_robustness"].items()
    ]
    return f"""## How honest is the number? (stricter splits)

{_table(["Split", "R²", "Mean abs error", "Typical error"], rows)}

*Grouped* keeps the same house out of both sides (177 houses sold twice).
*Temporal* trains on earlier sales and tests on later ones, like real use."""


def _errors(report: dict) -> str:
    bands = report["error_by_price_band"]
    return f"""## Where it errs (price quartiles, test set)

{_band_table(bands)}

{_bias_note(bands)}"""


def _estimator(report: dict) -> str:
    estimator = report["estimator"]
    lost = report["test_metrics"]["r2"] - estimator["test_metrics"]["r2"]
    interval = estimator["interval"]
    inputs = ", ".join(f"`{name}`" for name in estimator["inputs"])
    return f"""## The six-question estimator (what the website uses)

A visitor answers {len(estimator["inputs"])} everyday questions: {inputs}. Everything
else is filled with what is typical for the house's zip code, learned from training
data only (no basement and no renovation assumed).

{_metrics_table(estimator["test_metrics"])}

Accuracy given up by asking six questions instead of 19 columns: **{lost:.3f} R²**.
Floor for this model: {estimator["min_acceptable_r2"]:.2f}. Met.

**Price range shown to visitors.** The estimate is multiplied by
{interval["low_ratio"]:.2f} and {interval["high_ratio"]:.2f} to give a range meant to
hold the true price {interval["coverage"]:.0%} of the time. It was calibrated on
out-of-fold training predictions; on the untouched test set it held the true price
for {interval["test_coverage"]:.1%} of houses."""


def _limitations() -> str:
    return """## Limitations

- Prices are from 2014 to 2015; the market has moved. Treat output as relative, not
  current.
- Location features (zip code, coordinates, distances) can act as proxies for
  neighbourhood demographics. No fairness audit has been run, so do not use for
  credit or housing-eligibility decisions.
- The six-question estimator cannot see lot size, condition, view or renovations, so
  two very different houses with the same answers get the same estimate.
- Some outliers are data problems, not model problems (the notebook found a lot with
  no house on it)."""


def render_model_card(report: dict) -> str:
    sections = [
        _header(report),
        _data(report),
        _model(report),
        _performance(report),
        _comparison(report),
        _robustness(report),
        _errors(report),
        _estimator(report),
        _limitations(),
        f"## Deep-learning gate\n\n{_gate(report)}",
    ]
    return "\n\n".join(sections) + "\n"
