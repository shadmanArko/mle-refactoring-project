"""Render the model card from a training report, so docs never drift from numbers."""


def _table(headers: list[str], rows: list[list[str]]) -> str:
    lines = [
        "| " + " | ".join(headers) + " |",
        "|" + "|".join("---" for _ in headers) + "|",
    ]
    lines += ["| " + " | ".join(row) + " |" for row in rows]
    return "\n".join(lines)


def _usd(value: float) -> str:
    sign = "-" if round(value) < 0 else ""
    return f"{sign}${abs(value):,.0f}"


def _r2(value: float) -> str:
    return f"{value + 0.0:.3f}" if abs(value) >= 0.0005 else "0.000"


def _deep_learning_gate(report: dict) -> str:
    models = [row for row in report["comparison"] if row["role"] != "baseline"]
    best = max(models, key=lambda row: row["cv_r2_mean"])
    worst = min(models, key=lambda row: row["cv_r2_mean"])
    spread = best["cv_r2_mean"] - worst["cv_r2_mean"]
    floor = report["min_acceptable_r2"]
    verdict = "not_warranted" if best["cv_r2_mean"] >= floor else "conditional"
    production = next(row for row in models if row["role"] == "production")
    gap = best["cv_r2_mean"] - production["cv_r2_mean"]
    trailing = (
        ""
        if best is production
        else f" The shipped model trails it by {gap:.3f} cross-validated R²: "
        "a tuned tree ensemble is the next step before any neural network."
    )
    return (
        f"**Verdict: `{verdict}`.** The data is 19 tabular columns with no text or "
        f"images. The best classical model ({best['name']}) reaches a "
        f"cross-validated R² of {best['cv_r2_mean']:.3f} against a floor of "
        f"{floor:.2f}; the spread across classical families is {spread:.3f}."
        f"{trailing}\n\n"
        "Revisit if: the dataset grows past roughly 1 million sales, listing text or "
        "photos are added as inputs, or classical models stop clearing the floor "
        "after retraining."
    )


def render_model_card(report: dict) -> str:
    meta = report["metadata"]
    test = report["test_metrics"]

    comparison_rows = [
        [
            f"`{row['name']}`",
            row["role"],
            f"{_r2(row['cv_r2_mean'])} ± {row['cv_r2_std']:.3f}",
            _r2(row["test_r2"]) if "test_r2" in row else "not used",
        ]
        for row in report["comparison"]
    ]
    robustness_rows = [
        [
            name,
            f"{m['r2']:.3f}",
            _usd(m["mae"]),
            f"{m['median_abs_pct_error']:.1f}%",
        ]
        for name, m in report["split_robustness"].items()
    ]
    band_rows = [
        [
            f"{band['band']}",
            f"{_usd(band['price_min'])} to {_usd(band['price_max'])}",
            str(band["houses"]),
            f"{band['median_abs_pct_error']:.1f}%",
            _usd(band["mean_error"]),
        ]
        for band in report["error_by_price_band"]
    ]
    params = report["best_params"]

    return f"""# Model card: King County house price estimator

Generated by `kc_house.train` on {meta["trained_at"]} (git `{meta["git_sha"][:7]}`).
Every number below comes from `metrics.json`; do not edit by hand.

## Intended use

Give a rough sale-price estimate for a house in King County, Washington, to help a
buyer or seller judge a fair price. **Not** for appraisal, lending, insurance or any
decision with legal or financial consequences.

## Data

{meta["data_rows"]:,} house sales from {meta["sale_dates"][0]} to {
        meta["sale_dates"][1]
    }
(one year); one implausible record is removed. Split {meta["train_rows"]:,} train /
{meta["test_rows"]:,} test, seed {meta["random_state"]}. Dataset hash
`{meta["data_sha256"][:12]}`.

## Model

```mermaid
flowchart LR
    A[Raw house columns] --> B[Clean and engineer features]
    B --> C[Polynomial degree 2]
    C --> D[Scale]
    D --> E[ElasticNet on price]
```

ElasticNet with `alpha={params["model__regressor__alpha"]}` and
`l1_ratio={params["model__regressor__l1_ratio"]}`, chosen by
{meta["cv_folds"]}-fold grid search on training data only.

## Performance (held-out test set, evaluated once)

{
        _table(
            ["Metric", "Value"],
            [
                ["R²", f"{test['r2']:.3f}"],
                [
                    "Typical error (median)",
                    f"{test['median_abs_pct_error']:.1f}% of the price",
                ],
                ["Mean absolute error", _usd(test["mae"])],
                ["RMSE", _usd(test["rmse"])],
                ["Average bias", _usd(test["mean_error"])],
            ],
        )
    }

Stopping floor: held-out R² of at least {report["min_acceptable_r2"]:.2f}. Met.

## What it beat

{_table(["Model", "Role", "Cross-validated R²", "Test R²"], comparison_rows)}

Baselines are scored before any tuning. Other families are judged on
cross-validation only so the test set stays untouched.

## How honest is the number? (stricter splits)

{_table(["Split", "R²", "Mean abs error", "Typical error"], robustness_rows)}

*Grouped* keeps the same house out of both sides (177 houses sold twice).
*Temporal* trains on earlier sales and tests on later ones, like real use.

## Where it errs (price quartiles, test set)

{
        _table(
            ["Quartile", "Price range", "Houses", "Typical error", "Average bias"],
            band_rows,
        )
    }

## Limitations

- Prices are from 2014 to 2015; the market has moved. Treat output as relative, not
  current.
- Location features (zip code, coordinates, distances) can act as proxies for
  neighbourhood demographics. No fairness audit has been run, so do not use for
  credit or housing-eligibility decisions.
- The model pulls estimates toward the middle: cheap houses tend to be overestimated
  and the most expensive underestimated (see average bias by quartile).
- Some outliers are data problems, not model problems (the notebook found a lot with
  no house on it).

## Deep-learning gate

{_deep_learning_gate(report)}
"""
